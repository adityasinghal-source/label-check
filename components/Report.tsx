"use client";

import { useState } from "react";
import CopyButton from "@/components/CopyButton";
import FixAllPanel from "@/components/FixAllPanel";
import HighlightedLabel from "@/components/HighlightedLabel";
import { noIssuesHeading } from "@/lib/messages";
import { readiness } from "@/lib/summary";
import type { Flag, Report as ReportData } from "@/lib/types";

const SEVERITY_STYLE = {
  high: "bg-red-100 text-red-800",
  medium: "bg-amber-100 text-amber-800",
  low: "bg-sky-100 text-sky-800",
};

const TONE_STYLE = {
  red: "border-red-200 bg-red-50 text-red-900",
  amber: "border-amber-200 bg-amber-50 text-amber-900",
  green: "border-green-200 bg-green-50 text-green-900",
};

function FlagCard({ flag, id, selected, onSelect }: { flag: Flag; id: string; selected: boolean; onSelect: () => void }) {
  const fixLabel =
    flag.fix?.type === "allergen_statement"
      ? "Add this allergen line"
      : flag.foundBy === "ai"
        ? "Suggested rewrite (AI-written, check before using)"
        : "Suggested rewrite";

  return (
    <li
      id={id}
      onClick={onSelect}
      className={`cursor-pointer rounded-lg border bg-white p-4 ${selected ? "border-gray-900 ring-2 ring-gray-900" : "border-gray-200"}`}
    >
      <div className="flex flex-wrap items-center gap-2 text-xs">
        <span className={`rounded px-2 py-0.5 font-semibold uppercase ${SEVERITY_STYLE[flag.severity]}`}>{flag.severity}</span>
        <span className="font-mono text-gray-700">{flag.ruleId}</span>
        <span className="text-gray-700">{flag.ruleName}</span>
        <span className="ml-auto rounded bg-gray-100 px-2 py-0.5 text-gray-600">
          Found by: {flag.foundBy === "ai" ? "AI" : "rule check"}
        </span>
      </div>
      <p className="mt-3 text-lg">{flag.quotedText ? `“${flag.quotedText}”` : "Missing from the label"}</p>
      <p className="mt-1 text-sm text-gray-700">{flag.explanation}</p>
      <p className="mt-1 text-xs text-gray-500">{flag.citation}</p>
      {flag.suggestedRewrite ? (
        <div className="mt-3 rounded bg-green-50 p-3">
          <p className="text-xs font-semibold text-green-900">{fixLabel}</p>
          <div className="mt-1 flex items-start gap-3">
            <p className="flex-1 text-sm">{flag.suggestedRewrite}</p>
            <CopyButton text={flag.suggestedRewrite} />
          </div>
        </div>
      ) : (
        flag.advice && (
          <div className="mt-3 rounded bg-amber-50 p-3">
            <p className="text-xs font-semibold text-amber-900">What to do</p>
            <p className="mt-1 text-sm">{flag.advice}</p>
          </div>
        )
      )}
    </li>
  );
}

export default function Report({
  report,
  compact = false,
  onRecheck,
}: {
  report: ReportData;
  compact?: boolean;
  onRecheck?: (text: string) => void;
}) {
  const [selected, setSelected] = useState<number | null>(null);
  const summary = readiness(report.flags, report.packVersion);
  const noIssues = report.ruleStatuses.filter((r) => r.status === "no_issues");
  const notChecked = report.ruleStatuses.filter((r) => r.status === "not_checked");
  const allergensChecked = !notChecked.some((r) => r.note === "No ingredient list found");
  const cardId = (i: number) => `flag-${report.packId}-${i}`;

  function select(i: number) {
    setSelected(i);
    document.getElementById(cardId(i))?.scrollIntoView({ behavior: "smooth", block: "center" });
  }

  return (
    <section className="space-y-5">
      <div className={`rounded-lg border p-4 ${TONE_STYLE[summary.tone]}`}>
        <p className="text-xl font-bold">{summary.verdict}</p>
        <p className="mt-1 text-sm">{summary.counts}</p>
        <p className="mt-2 text-xs opacity-80">
          Checked against {report.packLabel} rule pack v{report.packVersion}
          {report.basedOn && ` (includes ${report.basedOn})`}
        </p>
      </div>

      {allergensChecked && (
        <div className="rounded-lg border border-gray-200 bg-white p-4">
          <p className="text-xs font-semibold uppercase text-gray-600">Allergen statement for your pack</p>
          {report.allergenStatement ? (
            <div className="mt-1 flex items-start gap-3">
              <p className="flex-1 text-lg font-semibold">{report.allergenStatement}</p>
              <CopyButton text={report.allergenStatement} />
            </div>
          ) : (
            <p className="mt-1 text-sm">No major allergens found in the ingredient list.</p>
          )}
          <p className="mt-1 text-xs text-gray-500">Generated by rule check from your ingredient list.</p>
        </div>
      )}

      <div>
        <p className="mb-1 text-xs font-semibold uppercase text-gray-600">
          Your label{report.flags.some((f) => f.quotedText) && ": click a highlighted phrase to see its rule and fix"}
        </p>
        <HighlightedLabel text={report.labelText} flags={report.flags} selected={selected} onSelect={select} />
      </div>

      {!compact && <FixAllPanel key={report.labelText + report.packId} report={report} onRecheck={onRecheck} />}

      {report.flags.length > 0 && (
        <ul className="space-y-3">
          {report.flags.map((flag, i) => (
            <FlagCard
              key={`${flag.ruleId}-${flag.quotedText}-${i}`}
              flag={flag}
              id={cardId(i)}
              selected={selected === i}
              onSelect={() => setSelected(i)}
            />
          ))}
        </ul>
      )}

      {report.droppedAiFlags > 0 && (
        <p className="text-sm text-gray-600">
          {report.droppedAiFlags} AI suggestion{report.droppedAiFlags > 1 ? "s were" : " was"} removed because it
          didn&apos;t cite a valid rule or quote your text.
        </p>
      )}

      {noIssues.length > 0 && (
        <div>
          <h3 className="font-semibold">{noIssuesHeading(report.packVersion)}</h3>
          <ul className="mt-1 text-sm text-gray-700">
            {noIssues.map((r) => (
              <li key={r.ruleId}>
                <span className="font-mono">{r.ruleId}</span> · {r.ruleName}
                {r.note && `: ${r.note}`}
              </li>
            ))}
          </ul>
        </div>
      )}

      {notChecked.length > 0 && (
        <div>
          <h3 className="font-semibold">Not checked</h3>
          <ul className="mt-1 text-sm text-gray-700">
            {notChecked.map((r) => (
              <li key={r.ruleId}>
                <span className="font-mono">{r.ruleId}</span> · {r.ruleName}: {r.note}
              </li>
            ))}
          </ul>
        </div>
      )}
    </section>
  );
}
